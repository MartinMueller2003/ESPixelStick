# Get CI version number
Import('env')
import os
import subprocess

version = "dev"

if "CI" in os.environ:
    with open("firmware/VERSION", "r") as file:
        version = file.readline().rstrip()
    env.Append(BUILD_FLAGS=[f"-DESPS_VERSION=\"{version}\""])

# The commit the image was built from, for the serial banner and the Admin page. It goes into a
# generated header that only main.cpp includes, so a new commit recompiles one file, not the tree.
# The version string itself is not touched. "-dirty" marks a tree with uncommitted source changes.
project_dir = env.subst("$PROJECT_DIR")
commit = ""
try:
    commit = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=project_dir, text=True).strip()[:8]
    changes = subprocess.check_output(["git", "status", "--porcelain", "--", "src", "include", "html", "platformio.ini"], cwd=project_dir, text=True).strip()
    if changes:
        commit += "-dirty"
except Exception:
    commit = ""
header_path = os.path.join(project_dir, "include", "BuildCommit.h")
header = "// Generated by .scripts/pio-version.py at build time. Not in git.\n#pragma once\n#define ESPS_BUILD_COMMIT \"%s\"\n" % commit
current = ""
try:
    with open(header_path, "r") as file:
        current = file.read()
except OSError:
    pass
if current != header:
    with open(header_path, "w") as file:
        file.write(header)
